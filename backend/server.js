import 'dotenv/config';
import express from 'express';
import cors from 'cors';
import authRoutes from './routes/auth.js';
import hotelRoutes from './routes/hotels.js';
import roomRoutes from './routes/rooms.js';
import bookingRoutes from './routes/bookings.js';
import wishlistRoutes from './routes/wishlist.js';
import userRoutes from './routes/users.js';
import ownerRoutes from './routes/owner.js';
const app=express();app.use(cors({origin:process.env.FRONTEND_ORIGIN||'http://localhost:5173'}));app.use(express.json());
app.get('/api/health',(_req,res)=>res.json({status:'ok',service:'HotelBook API'}));
app.use('/api/auth',authRoutes);app.use('/api/hotels',hotelRoutes);app.use('/api/rooms',roomRoutes);app.use('/api/bookings',bookingRoutes);app.use('/api/wishlist',wishlistRoutes);app.use('/api/users',userRoutes);app.use('/api/owner',ownerRoutes);
app.use((err,_req,res,_next)=>{console.error(err);res.status(500).json({message:'Unexpected server error'})});
const port=Number(process.env.PORT)||5000;app.listen(port,()=>console.log(`HotelBook API listening on ${port}`));
